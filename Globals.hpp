class BleScanCallbacks : public BLEAdvertisedDeviceCallbacks {
  void onResult(BLEAdvertisedDevice advertisedDevice) override {
    if (bleSnifferRunning) {
      blePktCount++;
      static unsigned long lastMs = 0;
      static unsigned long lastCount = 0;
      if (millis() - lastMs >= 1000) {
        blePktRate = blePktCount - lastCount;
        lastCount = blePktCount;
        lastMs = millis();
      }
      uint8_t a[6];
      memcpy(a, advertisedDevice.getAddress().getNative(), 6);
      bool known = false;
      for (int i = 0; i < snifferSeenCount; i++)
        if (memcmp(snifferSeen[i], a, 6) == 0) { known = true; break; }
      if (!known && snifferSeenCount < MAX_SNIFFER_UNIQUE)
        memcpy(snifferSeen[snifferSeenCount++], a, 6);
      bleSnifferUnique = snifferSeenCount;
      return;
    }
  }
};

