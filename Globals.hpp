class MyScanCB : public BLEAdvertisedDeviceCallbacks {
  void onResult(BLEAdvertisedDevice advertisedDevice) override {
    uint8_t mac[6];
    memcpy(mac, advertisedDevice.getAddress().getNative(), 6);

    int idx = -1;
    for (int i = 0; i < bleScanCount; i++)
      if (memcmp(bleDevices[i].address, mac, 6) == 0) { idx = i; break; }
    if (idx < 0 && bleScanCount < MAX_BLE_RESULTS)
      idx = bleScanCount++;

    if (idx < 0) return;

    bool isNew = !bleDevices[idx].updated;

    memcpy(bleDevices[idx].address, advertisedDevice.getAddress().getNative(), 6);
    bleDevices[idx].addrType = advertisedDevice.getAddressType();

    String n = advertisedDevice.getName().c_str();
    if (n.length() == 0) n = advertisedDevice.toString().c_str();
    if (n.length() == 0) n = "(unbenannt)";
    String addrStr = advertisedDevice.getAddress().toString().c_str();
    if (n.indexOf(addrStr) >= 0) n = addrStr;
    bleDevices[idx].name = n;

    bleScanMenu[idx] = n;
    if (isNew) memcpy(bleDeviceAddr[idx], mac, 6);

    BLEDeviceInfo &d = bleDevices[idx];
    d.rssi = advertisedDevice.getRSSI();
    d.appearance = advertisedDevice.haveAppearance() ? advertisedDevice.getAppearance() : 0;

    d.serviceCount = 0;
    String uuidStr = "";
    if (advertisedDevice.haveServiceUUID()) {
      String u = advertisedDevice.getServiceUUID().toString().c_str();
      if (d.serviceCount < 4) { d.serviceUuids[d.serviceCount++] = u; uuidStr += u + " "; }
    }

    d.manufacturerData = "";
    if (advertisedDevice.haveManufacturerData()) {
#if ESP_ARDUINO_VERSION_MAJOR >= 3
      String md = advertisedDevice.getManufacturerData();
#else
      std::string md = advertisedDevice.getManufacturerData();
#endif
      char hx[3];
      for (size_t i = 0; i < md.length() && i < 8; i++) {
        snprintf(hx, sizeof(hx), "%02X", (uint8_t)md[i]);
        d.manufacturerData += hx;
      }
    }

    d.deviceType = classifyBleDevice(d.appearance, d.name, uuidStr);

    d.lineCount = 0;
    d.lines[d.lineCount++] = "Typ: " + d.deviceType;
    d.lines[d.lineCount++] = "Name: " + d.name;
    char mb[18];
    snprintf(mb, sizeof(mb), "%02X:%02X:%02X:%02X:%02X:%02X",
             mac[0], mac[1], mac[2], mac[3], mac[4], mac[5]);
    d.lines[d.lineCount++] = "MAC: " + String(mb);
    d.lines[d.lineCount++] = String("Addr: ") + (d.addrType ? "Random" : "Public");
    d.lines[d.lineCount++] = "RSSI: " + String(d.rssi) + " dBm";
    if (advertisedDevice.haveTXPower())
      d.lines[d.lineCount++] = "TX-Pwr: " + String(advertisedDevice.getTXPower()) + " dBm";
    for (int i = 0; i < d.serviceCount && d.lineCount < 12; i++)
      d.lines[d.lineCount++] = "SVC: " + d.serviceUuids[i];
    if (d.manufacturerData.length())
      d.lines[d.lineCount++] = "Manuf: " + d.manufacturerData;

    bleDevices[idx].updated = true;
    bleScanDirty = true;
  }
};

