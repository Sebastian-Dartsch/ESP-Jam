String bleBytesToHex(const std::string &data) {
  String out = "";
  char buf[4];
  for (size_t i = 0; i < data.length() && i < 16; i++) {
    snprintf(buf, sizeof(buf), "%02X ", (uint8_t)data[i]);
    out += buf;
  }
  if (data.length() > 16) out += "...";
  return out;
}

#define MAX_SNIFFER_UNIQUE 20
