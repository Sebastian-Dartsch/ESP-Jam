void ensureWiFiOffForBLE() {
  if (WiFi.getMode() != WIFI_OFF) {
    WiFi.disconnect(true);
    WiFi.mode(WIFI_OFF);
    esp_wifi_deinit();
    wifiForcedOff = true;
    delay(100);
    Serial.printf("[RADIO] WiFi off, Heap: %u\n", ESP.getFreeHeap());
  }
}

